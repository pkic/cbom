"""Writes regulation/coverage.md from the regulatory sufficiency catalogue.

The catalogue in regulation/catalogue/ records, for each instrument, the
evidence questions a reader must answer and whether a CBOM that conforms to a
named profile answers them. This script turns it into one Markdown page: a
summary across instruments, a table for each instrument, and the list of gaps.

Usage: python3 tools/build_regulatory_coverage.py [--check]
With --check, the script writes nothing and exits with 1 if coverage.md is
out of date.
"""
import glob, os, sys
import yaml

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
CAT = os.path.join(ROOT, "regulation", "catalogue")
OUT = os.path.join(ROOT, "regulation", "coverage.md")
VERDICTS = ["sufficient", "deeper-profile", "partial", "judgement", "out-of-scope", "open"]
LABEL = {"sufficient": "Sufficient", "deeper-profile": "Deeper profile", "partial": "Partial",
         "judgement": "Judgement", "out-of-scope": "Out of scope", "open": "Open"}

def load():
    docs = []
    for path in sorted(glob.glob(os.path.join(CAT, "*.yaml"))):
        with open(path, encoding="utf8") as f:
            docs.append((os.path.basename(path), yaml.safe_load(f)))
    return docs

def short(profile_id):
    return profile_id.replace("pkic.example.", "")

def one_line(text):
    return " ".join(str(text or "").split())

def render(docs):
    out = ["# Regulatory sufficiency: coverage", "",
           "Generated by `tools/build_regulatory_coverage.py` from `regulation/catalogue/`. "
           "Do not edit this page by hand. The README in this folder explains the verdicts and the three levels.", "",
           "## Summary", "",
           "| Instrument | Questions | " + " | ".join(LABEL[v] for v in VERDICTS) + " |",
           "|---|---:|" + "---:|" * len(VERDICTS)]
    totals = {v: 0 for v in VERDICTS}
    for _, d in docs:
        qs = d["questions"]
        counts = {v: sum(1 for q in qs if q["verdict"] == v) for v in VERDICTS}
        for v in VERDICTS:
            totals[v] += counts[v]
        out.append(f"| {d['instrument']['title'].split(',')[0]} | {len(qs)} | "
                   + " | ".join(str(counts[v] or "") for v in VERDICTS) + " |")
    out.append(f"| **All instruments** | **{sum(totals.values())}** | "
               + " | ".join(f"**{totals[v]}**" for v in VERDICTS) + " |")
    out.append("")
    gaps = []
    for _, d in docs:
        ins = d["instrument"]
        out += [f"## {ins['title']}", "",
                f"{ins['jurisdiction']}, {ins['kind']}, {ins['published']}. Applies to: {one_line(ins['appliesTo'])}.", "",
                one_line(ins["summary"]), ""]
        if ins.get("source"):
            out += [f"Source: <{ins['source']}>", ""]
        out += ["| Id | Clause | Question | Evidence | Expressible | Required | Evaluable | Verdict | Checked |",
                "|---|---|---|---|---|---|---|---|---|"]
        for q in d["questions"]:
            ev = "; ".join(f"{short(e['profile'])} {', '.join(e['rules'])}" for e in q.get("evidence") or []) or "—"
            lv = q["levels"]
            out.append(f"| {q['id']} | {one_line(q['clause'])} | {one_line(q['question'])} | {ev} | "
                       f"{lv['expressible']} | {lv['required']} | {lv['evaluable']} | {LABEL[q['verdict']]} | {q['checked']} |")
            if q.get("gap"):
                gaps.append((q["id"], ins["title"].split(",")[0], one_line(q["gap"])))
        out.append("")
    out += ["## Gaps", "",
            "Each gap is either a candidate attribute for the methodology, or a statement of why the question stays outside a CBOM.", "",
            "| Question | Instrument | Gap |", "|---|---|---|"]
    out += [f"| {i} | {n} | {g} |" for i, n, g in gaps]
    return "\n".join(out) + "\n"

if __name__ == "__main__":
    text = render(load())
    if "--check" in sys.argv:
        current = open(OUT, encoding="utf8").read() if os.path.exists(OUT) else ""
        sys.exit(0 if current == text else 1)
    with open(OUT, "w", encoding="utf8") as f:
        f.write(text)
    print(f"wrote {os.path.relpath(OUT, ROOT)}")
