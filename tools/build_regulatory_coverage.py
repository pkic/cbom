"""Writes regulation/coverage.md and the site page docs/methodology/regulation.html
from the regulatory sufficiency catalogue.

The catalogue in regulation/catalogue/ records, for each instrument, the
evidence questions a reader must answer and whether a CBOM that conforms to a
named profile answers them. This script turns it into one Markdown page: a
summary across instruments, a table for each instrument, and the list of gaps.

Usage: python3 tools/build_regulatory_coverage.py [--check]
With --check, the script writes nothing and exits with 1 if either output is
out of date.
"""
import glob, html, os, sys
import yaml

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
CAT = os.path.join(ROOT, "regulation", "catalogue")
OUT = os.path.join(ROOT, "regulation", "coverage.md")
PAGE = os.path.join(ROOT, "docs", "methodology", "regulation.html")
REPO = "https://github.com/pkic/cbom/tree/main/regulation"
VERDICTS = ["sufficient", "deeper-profile", "partial", "judgement", "out-of-scope", "open"]
LABEL = {"sufficient": "Sufficient", "deeper-profile": "Deeper profile", "partial": "Partial",
         "judgement": "Judgement", "out-of-scope": "Out of scope", "open": "Open"}

def load():
    docs = []
    for path in sorted(glob.glob(os.path.join(CAT, "*.yaml"))):
        with open(path, encoding="utf8") as f:
            docs.append((os.path.basename(path), yaml.safe_load(f)))
    return docs

def short(profile_id):
    return profile_id.replace("pkic.example.", "")

def one_line(text):
    return " ".join(str(text or "").split())

def render(docs):
    out = ["# Regulatory sufficiency: coverage", "",
           "Generated by `tools/build_regulatory_coverage.py` from `regulation/catalogue/`. "
           "Do not edit this page by hand. The README in this folder explains the verdicts and the three levels.", "",
           "## Summary", "",
           "| Instrument | Questions | " + " | ".join(LABEL[v] for v in VERDICTS) + " |",
           "|---|---:|" + "---:|" * len(VERDICTS)]
    totals = {v: 0 for v in VERDICTS}
    for _, d in docs:
        qs = d["questions"]
        counts = {v: sum(1 for q in qs if q["verdict"] == v) for v in VERDICTS}
        for v in VERDICTS:
            totals[v] += counts[v]
        out.append(f"| {d['instrument']['title'].split(',')[0]} | {len(qs)} | "
                   + " | ".join(str(counts[v] or "") for v in VERDICTS) + " |")
    out.append(f"| **All instruments** | **{sum(totals.values())}** | "
               + " | ".join(f"**{totals[v]}**" for v in VERDICTS) + " |")
    out.append("")
    gaps = []
    for _, d in docs:
        ins = d["instrument"]
        out += [f"## {ins['title']}", "",
                f"{ins['jurisdiction']}, {ins['kind']}, {ins['published']}. Applies to: {one_line(ins['appliesTo'])}.", "",
                one_line(ins["summary"]), ""]
        if ins.get("source"):
            out += [f"Source: <{ins['source']}>", ""]
        out += ["| Id | Clause | Question | Evidence | Expressible | Required | Evaluable | Verdict | Checked |",
                "|---|---|---|---|---|---|---|---|---|"]
        for q in d["questions"]:
            ev = "; ".join(f"{short(e['profile'])} {', '.join(e['rules'])}" for e in q.get("evidence") or []) or "—"
            lv = q["levels"]
            out.append(f"| {q['id']} | {one_line(q['clause'])} | {one_line(q['question'])} | {ev} | "
                       f"{lv['expressible']} | {lv['required']} | {lv['evaluable']} | {LABEL[q['verdict']]} | {q['checked']} |")
            if q.get("gap"):
                gaps.append((q["id"], ins["title"].split(",")[0], one_line(q["gap"])))
        out.append("")
    out += ["## Gaps", "",
            "Each gap is either a candidate attribute for the methodology, or a statement of why the question stays outside a CBOM.", "",
            "| Question | Instrument | Gap |", "|---|---|---|"]
    out += [f"| {i} | {n} | {g} |" for i, n, g in gaps]
    return "\n".join(out) + "\n"


def render_page(docs):
    e = lambda t: html.escape(one_line(t))
    rows, totals = [], {v: 0 for v in VERDICTS}
    for _, d in docs:
        qs = d["questions"]
        c = {v: sum(1 for q in qs if q["verdict"] == v) for v in VERDICTS}
        for v in VERDICTS:
            totals[v] += c[v]
        rows.append(f'      <tr><td><a href="#{d["instrument"]["id"]}">{e(d["instrument"]["title"].split(",")[0])}</a></td>'
                    f'<td>{len(qs)}</td>' + "".join(f"<td>{c[v] or ''}</td>" for v in VERDICTS) + "</tr>")
    rows.append(f"      <tr><td><strong>All instruments</strong></td><td><strong>{sum(totals.values())}</strong></td>"
                + "".join(f"<td><strong>{totals[v]}</strong></td>" for v in VERDICTS) + "</tr>")
    head = "".join(f"<th>{LABEL[v]}</th>" for v in VERDICTS)
    out = ["---", "nav: regulation", "---", "<!DOCTYPE html>", '<html lang="en">', "<head>", '<meta charset="utf-8">',
           '<meta name="viewport" content="width=device-width, initial-scale=1">',
           "<title>CBOM Profiles — Regulation</title>", '<link rel="stylesheet" href="styles.css">', "</head>", "<body>",
           '<header class="site">', '  <div class="hbar">',
           '    <a class="brand" href="../"><span class="brand-mark">CBOM</span><span class="brand-text">Profiles</span></a>',
           '    <span class="hsep">/</span><span class="hsection">Methodology</span>',
           '    <a class="hback" href="../">&#8592; Working group site</a>', "  </div>", "</header>", "",
           '<div class="shell">', "{% include methodology-nav.html %}", "", "<main>",
           "  <!-- Generated by tools/build_regulatory_coverage.py from regulation/catalogue/. Do not edit by hand. -->",
           '  <div class="crumb">OPERATIONS</div>', "  <h1>Regulation</h1>",
           '  <p class="lead">Regulators and policy makers increasingly ask for a cryptographic inventory, but most instruments do not say what the inventory must contain. This register records, clause by clause, whether a CBOM that conforms to a named profile gives a reader the facts needed to show that an instrument is met. It is a living register, kept outside the release, because instruments change more often than the methodology does. Publication 3, section 16.4, describes the method.</p>',
           "  <h2>How an instrument is recorded</h2>",
           "  <p>Each clause is broken into <strong>evidence questions</strong>: things a reader must be able to answer to show that the clause is met. Each question names the profile rules that supply its facts, and is tested at three levels:</p>",
           "  <ul>",
           "    <li><strong>Expressible.</strong> Can the methodology's model express the facts? If not, the gap is in the methodology and leads to a candidate attribute.</li>",
           "    <li><strong>Required.</strong> Does a named profile require the facts? If not, a reader can still ask for them through a deeper profile.</li>",
           "    <li><strong>Evaluable.</strong> Can a policy compute the answer without a person's judgement? If not, the policy must hold an allow list, a threshold or the operator's input.</li>",
           "  </ul>",
           "  <p>Each question then gets one verdict:</p>",
           "  <table>", "    <thead><tr><th>Verdict</th><th>Meaning</th></tr></thead>", "    <tbody>",
           "      <tr><td>Sufficient</td><td>A CBOM that conforms to the profile named answers the question.</td></tr>",
           "      <tr><td>Deeper profile</td><td>The model has the facts, but only a deeper or more specific profile requires them.</td></tr>",
           "      <tr><td>Partial</td><td>The CBOM supplies part of the answer, and the operator supplies the rest.</td></tr>",
           '      <tr><td>Judgement</td><td>The CBOM supplies the facts, but the answer is a judgement that belongs in a versioned <a href="policy-evaluation.html">policy</a>.</td></tr>',
           "      <tr><td>Out of scope</td><td>The question is about an organisation or a process, and no CBOM can answer it.</td></tr>",
           "      <tr><td>Open</td><td>The text that defines the question has not been published yet.</td></tr>",
           "    </tbody>", "  </table>",
           "  <h2>Summary</h2>", "  <table>", f"    <thead><tr><th>Instrument</th><th>Questions</th>{head}</tr></thead>", "    <tbody>"]
    out += rows + ["    </tbody>", "  </table>"]
    gaps = []
    for _, d in docs:
        ins = d["instrument"]
        out += [f'  <h2 id="{ins["id"]}">{e(ins["title"])}</h2>',
                f"  <p>{e(ins['jurisdiction'])}, {e(ins['kind'])}, {e(ins['published'])}. Applies to: {e(ins['appliesTo'])}.</p>",
                f"  <p>{e(ins['summary'])}</p>"]
        if ins.get("source"):
            out.append(f'  <p>Source: <a href="{html.escape(ins["source"])}">{html.escape(ins["source"])}</a></p>')
        out += ["  <table>", "    <thead><tr><th>Question</th><th>Evidence</th><th>Levels</th><th>Verdict</th></tr></thead>", "    <tbody>"]
        for q in d["questions"]:
            ev = "<br>".join(f"<code>{short(x['profile'])}</code> {', '.join(x['rules'])}" for x in q.get("evidence") or []) or "&mdash;"
            lv = q["levels"]
            out.append(f"      <tr><td><strong>{e(q['id'])}</strong> ({e(q['clause'])})<br>{e(q['question'])}"
                       f"<br><small>{e(q['rationale'])}</small></td><td>{ev}</td>"
                       f"<td>expressible: {lv['expressible']}<br>required: {lv['required']}<br>evaluable: {lv['evaluable']}</td>"
                       f"<td>{LABEL[q['verdict']]}<br><small>checked: {q['checked']}</small></td></tr>")
            if q.get("gap"):
                gaps.append((q["id"], ins["title"].split(",")[0], q["gap"]))
        out += ["    </tbody>", "  </table>"]
    out += ["  <h2>Gaps</h2>",
            "  <p>Each gap is either a candidate attribute for the methodology, or a statement of why the question stays outside a CBOM.</p>",
            "  <table>", "    <thead><tr><th>Question</th><th>Instrument</th><th>Gap</th></tr></thead>", "    <tbody>"]
    out += [f"      <tr><td>{e(i)}</td><td>{e(n)}</td><td>{e(g)}</td></tr>" for i, n, g in gaps]
    out += ["    </tbody>", "  </table>",
            f'  <div class="banner">The register paraphrases each instrument in its own words and does not interpret it. It is not legal advice. Entries marked <em>checked: secondary</em> have been checked against a secondary source only, and are to be confirmed against the official text. The catalogue and its README are in the <a href="{REPO}">regulation folder</a> of the repository.</div>',
            "", '  <div class="pagenav">', "  </div>",
            '  <div class="foot">PKIC CBOM Profiles Working Group · draft for comment.</div>', "</main>", "</div>", "</body>", "</html>"]
    return "\n".join(out) + "\n"

def with_publication_banner(text):
    """The breadcrumb and banner that tools/sync-publication-map.py writes on every methodology
    page, computed by that script from docs/_data/methodology_pubmap.yml, so the two cannot differ."""
    import importlib.util
    spec = importlib.util.spec_from_file_location("pubmap", os.path.join(ROOT, "tools", "sync-publication-map.py"))
    pm = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(pm)
    pubs, pages = pm.read_data()
    entry = next(p for p in pages if p["id"] == "regulation")
    text = pm.CRUMB.sub(pm.crumb(entry, pubs[entry["pub"]]), text, count=1)
    return pm.H1_END.sub("</h1>" + pm.banner(entry, pubs[entry["pub"]]), text, count=1)


if __name__ == "__main__":
    docs = load()
    outputs = {OUT: render(docs), PAGE: with_publication_banner(render_page(docs))}
    if "--check" in sys.argv:
        for path, text in outputs.items():
            current = open(path, encoding="utf8").read() if os.path.exists(path) else ""
            if path == PAGE:
                # The footer links are maintained by tools/renumber-pagenav.py.
                import re
                strip = lambda t: re.sub(r'<div class="pagenav">.*?</div>', "", t, flags=re.S)
                current, text = strip(current), strip(text)
            if current != text:
                sys.exit(1)
        sys.exit(0)
    for path, text in outputs.items():
        if path == PAGE and os.path.exists(PAGE):
            import re
            old = re.search(r'<div class="pagenav">.*?</div>', open(PAGE, encoding="utf8").read(), re.S)
            if old:
                text = re.sub(r'<div class="pagenav">.*?</div>', lambda m: old.group(0), text, flags=re.S)
        with open(path, "w", encoding="utf8") as f:
            f.write(text)
        print(f"wrote {os.path.relpath(path, ROOT)}")
